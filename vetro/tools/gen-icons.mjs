// Generates vetro/shell/src/icons_phosphor.h from Phosphor Icons (MIT), Regular weight.
//
//   node vetro/tools/gen-icons.mjs <path-to-@phosphor-icons/core>/assets/regular
//
// Only the icons the shell names are embedded, as their upstream path data in the native
// 256-unit viewbox. Nothing is redrawn here: icons Phosphor lacks are drawn by hand in
// icons_custom.h on the same grid and stroke.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = [
  // tools
  'arrows-out-cardinal', 'selection', 'lasso', 'magic-wand', 'crop', 'eyedropper', 'bandaids',
  'paint-brush', 'pencil-simple', 'stamp', 'clock-counter-clockwise', 'eraser', 'paint-bucket',
  'gradient', 'drop', 'sun', 'pen-nib', 'text-t', 'cursor', 'rectangle', 'hand', 'magnifying-glass',
  'frame-corners', 'ruler', 'note', 'circle', 'triangle', 'polygon', 'line-segment', 'star',
  'arrows-clockwise', 'scissors', 'bezier-curve', 'spray-bottle', 'drop-half', 'circle-half',
  'selection-plus', 'crosshair', 'paint-roller', 'hash', 'cursor-click', 'path', 'spiral',
  // layers and panels
  'eye', 'eye-slash', 'lock-simple', 'folder-simple', 'plus', 'trash', 'sliders-horizontal', 'stack',
  'image', 'square-half', 'link', 'mask-happy', 'text-aa', 'palette', 'swap', 'faders',
  // shell
  'x', 'minus', 'check', 'caret-right', 'caret-down', 'caret-left', 'dots-three', 'dots-six-vertical',
  'arrow-counter-clockwise', 'arrow-clockwise', 'copy', 'clipboard', 'floppy-disk', 'folder-open',
  'export', 'file-plus', 'magnifying-glass-plus', 'magnifying-glass-minus', 'corners-out', 'corners-in',
  'info', 'gear', 'squares-four', 'arrows-in', 'sparkle', 'square', 'copy-simple', 'browsers',
  'selection-all', 'selection-slash', 'selection-inverse', 'funnel', 'lightning', 'aperture',
  'warning-circle', 'check-circle', 'clock', 'list', 'question', 'grid-four',
  // retouching, paths, transform, Liquify
  'first-aid', 'arrows-out', 'arrow-line-left', 'snowflake', 'fire', 'waves', 'hand-swipe-right',
  'bounding-box', 'vector-two', 'selection-background', 'paint-brush-household',
];

const [dir] = process.argv.slice(2);
if (!dir) {
  console.error('usage: node gen-icons.mjs <phosphor>/assets/regular');
  process.exit(2);
}
const ident = (n) => 'Ph' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
let out = `#pragma once
// Phosphor Icons, Regular weight (MIT, (c) Phosphor Icons, see third_party/phosphor/LICENSE).
// Generated by vetro/tools/gen-icons.mjs -- do not edit. Upstream path data, 256-unit viewbox,
// filled with the nonzero rule.
`;
for (const name of NAMES) {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${name}: no path`);
  out += `inline const wchar_t* ${ident(name)}=L"${paths.join(' ')}";\n`;
}
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'shell', 'src', 'icons_phosphor.h');
writeFileSync(target, out);
console.log(`${NAMES.length} icons -> ${target}`);
